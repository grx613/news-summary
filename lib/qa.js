const TITLE_RULES = `title — заголовок страницы по сути вопроса: 30-90 символов, с названием актива или тикера, без кавычек, без мата, сленга и опечаток вопроса. Перепиши вопрос как заголовок статьи: «Дивиденды Сбербанка по итогам 2026 года», а не «скока дивов ждать??».`;

// ---------------------------------------------------------------- промпт для поиска
// Поисковая модель сама ходит в интернет, поэтому ей не нужен список публикаций из кеша:
// наоборот, грузить 30 заголовков в промпт вредно — они тянут ответ к нашему корпусу.
export function buildSearchPrompt({ asset, rec, question }) {
  const s = rec?.summary || {};
  const context = [
    s.headline && `Последняя сводка по активу: ${s.headline}`,
    s.overview && s.overview.slice(0, 400),
  ]
    .filter(Boolean)
    .join('\n');

  return `Актив: ${asset.name} (${asset.symbol}), рынок: ${asset.market}.
Сегодня ${new Date().toISOString().slice(0, 10)}.

Вопрос инвестора: «${question}»
${context ? `\n${context}\n` : ''}
Найди в интернете актуальные данные, чтобы ответить: отчётность, официальные сообщения компании, цифры регуляторов, оценки аналитиков. Приоритет — источники за последние 1-3 месяца и первоисточники (отчётность компании, биржа, ЦБ, ведомства), а не пересказы.

${VERDICT_RULES}

Правила ответа:
- Каждый факт, цифра и дата должны быть подтверждены найденным источником. Не переноси в ответ цифры, которых нет в источниках.
- Если данных по вопросу нет или они противоречивы — скажи прямо, чего не хватает, и что известно достоверно.
- Не давай персональных рекомендаций «покупать/продавать» и не обещай доходность: ты объясняешь ситуацию, а не управляешь деньгами.
- Если актив — российский, отдавай предпочтение российским источникам; указывай валюту и период цифр.
- Пиши простым текстом, без markdown: никаких **звёздочек**, решёток и таблиц.
- Пиши по-русски. Англицизмы не переноси из источников механически: «core search» → «основной поисковый бизнес», «cloud» → «облачный сегмент», «free cash flow» → «свободный денежный поток», «guidance» → «прогноз компании», «capex» → «капитальные затраты», «big tech» → «крупнейшие технологические компании», «postmarket» → «после закрытия торгов». Латиницей — только названия компаний, тикеры, продукты и устоявшиеся аббревиатуры (IPO, ETF, P/E, EBITDA). Названия сегментов бизнеса переводи.
- Абзацы разделяй пустой строкой.

${TITLE_RULES}
answer — 2-4 абзаца по существу вопроса, конкретно и с цифрами.
bullets — 2-4 коротких вывода, каждый самостоятельный.
confidence — насколько источники позволяют ответить: high, medium или low.`;
}

// ---------------------------------------------------------------- промпт по кешу
export function buildQaPrompt({ asset, rec, question }) {
  const list = (rec.news || [])
    .map((n, i) => `[${i + 1}] ${n.title}${n.source ? ` — ${n.source}` : ''}${n.published ? ` (${n.published})` : ''}`)
    .join('\n');

  const s = rec.summary || {};
  const known = [
    s.headline && `Главное: ${s.headline}`,
    s.overview && `Обзор: ${s.overview}`,
    s.key_points?.length &&
      'Ключевое: ' + s.key_points.map((k) => (typeof k === 'string' ? k : k.text)).join('; '),
    s.risks?.length && 'Риски: ' + s.risks.join('; '),
    s.catalysts?.length && 'Драйверы: ' + s.catalysts.join('; '),
  ]
    .filter(Boolean)
    .join('\n');

  return `Актив: ${asset.name} (${asset.symbol}), рынок: ${asset.market}.

Вопрос инвестора: «${question}»

Ранее сделанная сводка по этому активу:
${known || '(сводки нет)'}

Публикации за последние ${rec.windowHours || 72} ч:
${list}

${VERDICT_RULES}

Ответь на вопрос строго по этим материалам. Если в материалах нет данных для прямого ответа — так и напиши: чего не хватает и на что опираться. Не выдумывай цифры, даты и события, которых нет в подборке. Не давай персональных рекомендаций «покупать/продавать» и не обещай доходность: ты объясняешь ситуацию, а не управляешь деньгами. Посты Reddit — мнения частных инвесторов, помечай их как мнения. Пиши простым текстом без markdown, абзацы разделяй пустой строкой.

${TITLE_RULES}
answer — 2-4 абзаца по делу, без вступлений и повторов вопроса.
bullets — 2-4 коротких вывода, каждый самостоятельный.
refs — номера публикаций из списка, на которые опирается ответ.
confidence — насколько материалов достаточно: high, medium или low.`;
}
